//! The signed-build resource (CONTRACT G.4 c, DESIGN §4.15): with
//! `signing.enabled`, a Windows release build links the `OWEINTEGRITY/OWE`
//! PE resource `{"appUid":"<uid>"}` after checking the `ow-tauri sign`
//! output (`<project>/signed/sign-result.json`) against the merged-config
//! identity.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde_json::Value;
use sha2::{Digest as _, Sha256};

use super::{BuildError, BuildIdentity, file_error};
use crate::identity::is_valid_uid;

/// The resource data file in `OUT_DIR`.
pub(crate) const OWE_JSON_FILE: &str = "ow-tauri-owe.json";
/// The resource script in `OUT_DIR`.
pub(crate) const OWE_RC_FILE: &str = "ow-tauri-owe.rc";
/// The folder `ow-tauri sign` writes, relative to the Tauri folder.
pub(crate) const SIGNED_DIR: &str = "../signed";
/// The summary `ow-tauri sign` writes into [`SIGNED_DIR`].
pub(crate) const SIGN_RESULT_FILE: &str = "sign-result.json";

/// Escapes a value for a quoted `.rc` string.
fn rc_escape(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for c in value.chars() {
        match c {
            '"' => out.push_str("\"\""),
            '\\' => out.push_str("\\\\"),
            c => out.push(c),
        }
    }
    out
}

/// Writes the `OWEINTEGRITY/OWE` resource of `uid` into `out_dir`: the data
/// `{"appUid":"<uid>"}`, as Overwolf's builder writes it, and a resource
/// script naming it. The resource uses the neutral language (the version
/// information language tauri-build writes) and is its own type, so no
/// second `VERSIONINFO` is added. Returns the script's path.
pub(crate) fn owe_resource(uid: &str, out_dir: &Path) -> Result<PathBuf, BuildError> {
    if !is_valid_uid(uid) {
        return Err(BuildError::Signing(format!("invalid uid {uid:?}")));
    }
    let json_path = std::path::absolute(out_dir.join(OWE_JSON_FILE))
        .map_err(|e| file_error(&out_dir.join(OWE_JSON_FILE), e))?;
    // The uid is ASCII letters and digits: no JSON escaping needed.
    super::nsis::write_if_changed(&json_path, format!(r#"{{"appUid":"{uid}"}}"#).as_bytes())?;
    let rc = format!(
        "// Generated by tauri-plugin-overwolf (CONTRACT G.4 c).\nLANGUAGE 0, 0\nOWE OWEINTEGRITY \"{}\"\n",
        rc_escape(&json_path.to_string_lossy())
    );
    let rc_path = out_dir.join(OWE_RC_FILE);
    super::nsis::write_if_changed(&rc_path, rc.as_bytes())?;
    Ok(rc_path)
}

/// What [`check_signed`] found.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum Signed {
    /// The output matches the build; `warnings` (a changed entry file).
    Ready {
        /// Non-fatal findings.
        warnings: Vec<String>,
    },
    /// No usable output; why.
    Missing(String),
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().fold(String::new(), |mut s, b| {
        let _ = write!(s, "{b:02x}");
        s
    })
}

/// Checks `<signed_dir>/sign-result.json` against the build's identity:
/// the signed uid must be the merged-config uid (PAR-B2; `ow-tauri sign
/// --write-uid` pins it) and the version the build's. An entry file that
/// changed since it was hashed is a warning.
///
/// # Errors
///
/// [`BuildError::Signing`] when the signed uid differs: that build would
/// record one uid and run under another.
pub(crate) fn check_signed(signed_dir: &Path, id: &BuildIdentity) -> Result<Signed, BuildError> {
    let path = signed_dir.join(SIGN_RESULT_FILE);
    let Ok(text) = std::fs::read_to_string(&path) else {
        return Ok(Signed::Missing(format!(
            "{} is missing; run `ow-tauri sign` before a release build",
            path.display()
        )));
    };
    let Ok(result) = serde_json::from_str::<Value>(&text) else {
        return Ok(Signed::Missing(format!(
            "{} does not parse; run `ow-tauri sign` again",
            path.display()
        )));
    };
    let field = |k: &str| result.get(k).and_then(Value::as_str).unwrap_or_default();
    let uid = field("uid");
    if uid != id.uid {
        return Err(BuildError::Signing(format!(
            "the console signed uid {uid} but plugins.overwolf resolves to {}; set plugins.overwolf.uid to \"{uid}\" (or run ow-tauri sign --write-uid)",
            id.uid
        )));
    }
    let version = field("version");
    if Some(version) != id.version.as_deref() {
        return Ok(Signed::Missing(format!(
            "{} was signed for version \"{version}\", not \"{}\"; run `ow-tauri sign` again",
            path.display(),
            id.version.as_deref().unwrap_or_default()
        )));
    }
    let mut warnings = Vec::new();
    let (main, sha) = (field("mainPath"), field("mainSha256"));
    if !main.is_empty() {
        match std::fs::read(main) {
            Ok(bytes) if hex(&Sha256::digest(&bytes)).eq_ignore_ascii_case(sha) => {}
            Ok(_) => warnings.push(format!(
                "{} changed since `ow-tauri sign` hashed it; run `ow-tauri sign` again",
                field("mainFile")
            )),
            Err(_) => warnings.push(format!(
                "{} ({main}), which `ow-tauri sign` hashed, cannot be read; run `ow-tauri sign` again",
                field("mainFile")
            )),
        }
    }
    Ok(Signed::Ready { warnings })
}

/// Whether `bundle.resources` ships the signed `integrity.dll`.
pub(crate) fn ships_integrity_dll(merged: &Value) -> bool {
    match merged.pointer("/bundle/resources") {
        Some(Value::Array(items)) => items
            .iter()
            .filter_map(Value::as_str)
            .any(|item| item.contains("integrity.dll") || item.contains("signed/")),
        Some(Value::Object(map)) => map.iter().any(|(from, to)| {
            from.contains("integrity.dll") || to.as_str() == Some("integrity.dll")
        }),
        _ => false,
    }
}

/// Links the resource script into the app's executables.
pub(crate) fn link(rc: &Path) -> Result<(), BuildError> {
    embed_resource::compile(rc, embed_resource::NONE)
        .manifest_required()
        .map_err(|e| BuildError::Signing(format!("linking the OWEINTEGRITY resource failed: {e}")))
}

#[cfg(test)]
mod tests {
    use serde_json::json;

    use super::*;

    const UID: &str = "abcdefghijklmnopabcdefghijklmnop";

    fn id(version: &str) -> BuildIdentity {
        BuildIdentity {
            uid: UID.into(),
            cuid: UID.into(),
            name: "Example App".into(),
            author: "Example Studio".into(),
            version: Some(version.into()),
        }
    }

    fn temp(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("ow-tauri-owe-{}-{name}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn resource_files() {
        let dir = temp("rc");
        let rc = owe_resource(UID, &dir).unwrap();
        assert_eq!(
            std::fs::read_to_string(dir.join(OWE_JSON_FILE)).unwrap(),
            format!(r#"{{"appUid":"{UID}"}}"#)
        );
        let text = std::fs::read_to_string(&rc).unwrap();
        assert!(
            text.contains("LANGUAGE 0, 0\nOWE OWEINTEGRITY \""),
            "{text}"
        );
        assert!(owe_resource("../x", &dir).is_err());
        assert_eq!(rc_escape(r#"C:\a "b""#), r#"C:\\a ""b"""#);
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn signed_output_checks() {
        let dir = temp("signed");
        assert!(matches!(
            check_signed(&dir, &id("1.0.0")).unwrap(),
            Signed::Missing(_)
        ));
        let main = dir.join("main.js");
        std::fs::write(&main, "x").unwrap();
        let result = |uid: &str, version: &str, sha: &str| {
            std::fs::write(
                dir.join(SIGN_RESULT_FILE),
                json!({
                    "uid": uid, "version": version, "mainFile": "main.js",
                    "mainPath": main.to_string_lossy(), "mainSha256": sha
                })
                .to_string(),
            )
            .unwrap();
        };
        let sha = hex(&Sha256::digest(b"x"));
        result(UID, "1.0.0", &sha);
        assert_eq!(
            check_signed(&dir, &id("1.0.0")).unwrap(),
            Signed::Ready { warnings: vec![] }
        );
        // The signing-uid mismatch (PAR-B2) fails the build.
        result("zzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzz", "1.0.0", &sha);
        let err = check_signed(&dir, &id("1.0.0")).unwrap_err();
        assert!(err.to_string().contains("--write-uid"), "{err}");
        // Another version: unusable. A changed entry file: a warning.
        result(UID, "0.9.0", &sha);
        assert!(matches!(
            check_signed(&dir, &id("1.0.0")).unwrap(),
            Signed::Missing(_)
        ));
        result(UID, "1.0.0", &"0".repeat(64));
        match check_signed(&dir, &id("1.0.0")).unwrap() {
            Signed::Ready { warnings } => assert!(warnings[0].contains("changed"), "{warnings:?}"),
            other @ Signed::Missing(_) => panic!("{other:?}"),
        }
        std::fs::write(dir.join(SIGN_RESULT_FILE), "{").unwrap();
        assert!(matches!(
            check_signed(&dir, &id("1.0.0")).unwrap(),
            Signed::Missing(_)
        ));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn integrity_dll_resource() {
        assert!(ships_integrity_dll(
            &json!({ "bundle": { "resources": ["../signed/integrity.dll"] } })
        ));
        assert!(ships_integrity_dll(
            &json!({ "bundle": { "resources": { "../signed/integrity.dll": "integrity.dll" } } })
        ));
        assert!(!ships_integrity_dll(
            &json!({ "bundle": { "resources": ["assets/*"] } })
        ));
        assert!(!ships_integrity_dll(&json!({})));
    }
}
